package com.cruiseapp.util

fun wmoToDescription(code: Int?): String = when(code){
    0 -> "Clear sky"
    1 -> "Mainly clear"
    2 -> "Partly cloudy"
    3 -> "Overcast"
    45,48 -> "Fog"
    51 -> "Light drizzle"
    53 -> "Moderate drizzle"
    55 -> "Dense drizzle"
    56,57 -> "Freezing drizzle"
    61 -> "Slight rain"
    63 -> "Moderate rain"
    65 -> "Heavy rain"
    66,67 -> "Freezing rain"
    71 -> "Slight snow"
    73 -> "Moderate snow"
    75 -> "Heavy snow"
    77 -> "Snow grains"
    80 -> "Slight showers"
    81 -> "Moderate showers"
    82 -> "Violent showers"
    85,86 -> "Snow showers"
    95 -> "Thunderstorm"
    96,99 -> "Thunderstorm with hail"
    else -> "Unknown"
}

fun wmoToEmoji(code: Int?): String = when(code){
    0 -> "☀️"
    1 -> "🌤️"
    2 -> "⛅"
    3 -> "☁️"
    45,48 -> "🌫️"
    51,53,55,56,57 -> "🌦️"
    61,63,65,66,67 -> "🌧️"
    71,73,75,77,85,86 -> "❄️"
    80,81,82 -> "🌦️"
    95,96,99 -> "⛈️"
    else -> "🌡️"
}
